import 'dart:convert';

import 'output.dart';

String _esc(String s) => const HtmlEscape(HtmlEscapeMode.attribute).convert(s);

/// Builds `gallery.html`: every image of the run on one page, grouped by
/// template, locale and device.
String buildGallery({required String appName, required List<ShotRecord> shots, required Duration took}) {
  final byGroup = <String, List<ShotRecord>>{};
  for (final s in shots) {
    byGroup.putIfAbsent('${s.template} · ${s.theme} · ${s.locale} · ${s.device}', () => []).add(s);
  }
  final b = StringBuffer()
    ..writeln('<!doctype html><html lang="en"><head><meta charset="utf-8">')
    ..writeln('<meta name="viewport" content="width=device-width,initial-scale=1">')
    ..writeln('<title>${_esc(appName)} · store_shots</title><style>')
    ..writeln(
      ':root{color-scheme:light dark}body{margin:0;font:15px/1.5 system-ui,-apple-system,Segoe UI,Roboto,sans-serif;background:#0f1115;color:#e8eaed}',
    )
    ..writeln('header{padding:32px 40px 8px}h1{margin:0;font-size:28px}header p{margin:4px 0 0;color:#9aa0a6}')
    ..writeln(
      'section{padding:16px 40px}h2{font-size:15px;font-weight:600;color:#c4c7ce;margin:24px 0 12px;letter-spacing:.02em}',
    )
    ..writeln('.row{display:flex;gap:16px;overflow-x:auto;padding-bottom:8px}figure{margin:0;flex:none}')
    ..writeln(
      'img{height:420px;border-radius:14px;box-shadow:0 8px 30px rgba(0,0,0,.45);display:block;background:#222}',
    )
    ..writeln('img.wide{height:220px}figcaption{font-size:12px;color:#9aa0a6;margin-top:6px}a{color:inherit}')
    ..writeln('</style></head><body>')
    ..writeln(
      '<header><h1>${_esc(appName)}</h1><p>${shots.length} images · generated by store_shots in '
      '${(took.inMilliseconds / 1000).toStringAsFixed(1)}s</p></header>',
    );
  byGroup.forEach((group, list) {
    b
      ..writeln('<section><h2>${_esc(group)}</h2><div class="row">')
      ..writeAll([
        for (final s in list)
          '<figure><a href="${_esc(s.path)}"><img loading="lazy" class="${s.width > s.height ? 'wide' : ''}" '
              'src="${_esc(s.path)}" alt="${_esc(s.screen)}"></a><figcaption>${_esc(s.screen)} · ${s.width}×${s.height}'
              '</figcaption></figure>',
      ], '\n')
      ..writeln('</div></section>');
  });
  b.writeln('</body></html>');
  return b.toString();
}
